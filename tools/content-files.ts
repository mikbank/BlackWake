import {
  readFileSync,
  existsSync,
  mkdirSync,
  writeFileSync,
  renameSync,
  unlinkSync
} from 'node:fs';
import { join, dirname } from 'node:path';
import {
  universeDefinition,
  catalogFromData,
  contentId,
  type UniverseBundle
} from '../src/content/data';
import type { SystemDefinition } from '../src/content/schema';
export type ContentFiles = UniverseBundle;
/**
 * Serialize authored data with stable indentation and a trailing newline for readable
 * content diffs.
 */
export const json = (value: unknown) => JSON.stringify(value, null, 2) + '\n';
/**
 * Read the manifest's ordered system files and validate the complete bundle before a tool
 * operates on it.
 */
export function readContent(root: string): ContentFiles {
  const definition = universeDefinition(
      JSON.parse(readFileSync(join(root, 'universe.json'), 'utf8'))
    ),
    systems = definition.systemIds.map(
      /** Read each manifest-listed system file in its authoritative order. */
      (id) =>
        JSON.parse(
          readFileSync(join(root, 'systems', contentId(id) + '.json'), 'utf8')
        ) as SystemDefinition
    );
  catalogFromData(definition, systems);
  return { definition, systems };
}
/**
 * Generate deterministic static JSON imports so browser builds and Node authoring tools
 * load the same system list.
 */
export function importIndex(ids: string[]) {
  return (
    '// Generated by tools/universe.ts. Edit content/systems/*.json instead.\n' +
    ids
      .map(
        /** Generate a static JSON import for this stable system ID. */
        (id, i) =>
          `import system${i} from '../../content/systems/${contentId(id)}.json' with {type:'json'};`
      )
      .join('\n') +
    '\nexport const systemDefinitions:unknown[]=[' +
    ids
      .map(
        /** Generate the ordered binding names included in the browser's system-definition array. */
        (_, i) => `system${i}`
      )
      .join(',') +
    '];\n'
  );
}
/** Validate the bundle and calculate every output document before touching the filesystem. */
export function plannedWrites(root: string, files: ContentFiles) {
  catalogFromData(files.definition, files.systems);
  const writes = new Map<string, string>([
    [join(root, 'universe.json'), json(files.definition)],
    [
      join(dirname(root), 'src', 'content', 'system-index.ts'),
      importIndex(files.definition.systemIds)
    ]
  ]);
  for (const s of files.systems) writes.set(join(root, 'systems', s.id + '.json'), json(s));
  return writes;
}
/**
 * Write only changed documents; dry runs report paths and failed writes attempt to restore
 * previously written files.
 */
export function writeContent(root: string, files: ContentFiles, dryRun = false) {
  const planned = plannedWrites(root, files),
    changes = new Map<string, { before: string | null; after: string }>();
  for (const [path, after] of planned) {
    const before = existsSync(path) ? readFileSync(path, 'utf8') : null;
    const equal =
      path.endsWith('.json') && before !== null
        ? JSON.stringify(JSON.parse(before)) === JSON.stringify(JSON.parse(after))
        : before === after;
    if (!equal) changes.set(path, { before, after });
  }
  if (dryRun) return [...changes.keys()];
  const written: string[] = [];
  try {
    for (const [path, { after }] of changes) {
      mkdirSync(dirname(path), { recursive: true });
      const temp = path + '.pending';
      try {
        writeFileSync(temp, after);
        renameSync(temp, path);
        written.push(path);
      } finally {
        if (existsSync(temp)) unlinkSync(temp);
      }
    }
  } catch (error) {
    for (const path of written.reverse()) {
      const before = changes.get(path)!.before;
      if (before === null) unlinkSync(path);
      else writeFileSync(path, before);
    }
    throw error;
  }
  return [...changes.keys()];
}
